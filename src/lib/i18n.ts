let currentLang = 'de';

export function setLanguage(lang: 'de' | 'en') {
  currentLang = lang;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let text = translations[currentLang]?.[key] || translations['de']?.[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getAvailableVoices(): SpeechSynthesisVoice[] {
  if (typeof window === 'undefined' || !window.speechSynthesis) return [];
  return window.speechSynthesis.getVoices();
}

export function speak(text: string, voice?: string, rate?: number, volume?: number): SpeechSynthesisUtterance | null {
  if (typeof window === 'undefined' || !window.speechSynthesis) return null;
  const utterance = new SpeechSynthesisUtterance(text);
  const voices = getAvailableVoices();
  if (voice) {
    const v = voices.find(v => v.name === voice);
    if (v) utterance.voice = v;
  }
  if (rate) utterance.rate = rate;
  if (volume) utterance.volume = volume / 100;
  utterance.lang = currentLang === 'de' ? 'de-DE' : 'en-US';
  window.speechSynthesis.speak(utterance);
  return utterance;
}
